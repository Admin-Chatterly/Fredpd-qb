// Generates db/install.sql: every db/migrations/*.sql and db/seed/*.sql in runner order as ONE plain SQL file that
// can be run in HeidiSQL (or `mariadb < db/install.sql`). Each file is also recorded in fredpd_migrations with the
// same checksum the runners compute, so fredpd_core sees everything as applied and does not run it again.
// The `-- @if-table-exists` directive (runner-only) is rewritten to plain `ALTER TABLE IF EXISTS … ADD INDEX IF NOT
// EXISTS …`, so the file needs no runner. Re-running install.sql is safe (IF NOT EXISTS / upserts everywhere).
// Usage: node scripts/gen-install-sql.mjs [--check]   (--check exits 1 when db/install.sql is stale)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import {
  MIGRATIONS_DIR, SEED_DIR, MIGRATION_FILE_RE, SEED_FILE_RE, SEED_ID_PREFIX, MIGRATIONS_TABLE_DDL,
  listSqlFiles, normalizeBytes, checksum,
} from './migrate.mjs';

const OUT = join(import.meta.dirname, '..', 'db', 'install.sql');

/** `-- @if-table-exists T` + `CREATE INDEX IF NOT EXISTS i ON T (cols);` → one self-guarding statement. */
function rewriteDirectives(text, id) {
  return text.replace(
    /^--[ \t]*@if-table-exists[ \t]+([A-Za-z0-9_$]+)[ \t]*\n(\s*)CREATE INDEX IF NOT EXISTS ([A-Za-z0-9_$]+) ON ([A-Za-z0-9_$]+) (\([^;]*\));/gm,
    (_m, table, ws, index, onTable, cols) => {
      if (table !== onTable) throw new Error(`${id}: @if-table-exists ${table} guards an index on ${onTable}`);
      return `-- (runner directive @if-table-exists ${table}, rewritten for plain SQL)\n${ws}ALTER TABLE IF EXISTS ${table} ADD INDEX IF NOT EXISTS ${index} ${cols};`;
    },
  ).replace(/^--[ \t]*@if-table-exists.*$/gm, (line) => {
    throw new Error(`${id}: unsupported directive for install.sql: ${line}`);
  });
}

const sqlString = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

function build() {
  const parts = [
    '-- SPDX-License-Identifier: GPL-3.0-only',
    '-- FredPD — full database install for HeidiSQL / mariadb CLI. GENERATED by scripts/gen-install-sql.mjs; do not edit.',
    '-- Run it in the SAME database as qbx_core (select it in HeidiSQL first), then start the server.',
    '-- Safe to run again. fredpd_core records every file below as applied and will not re-run it.',
    '',
    'SET NAMES utf8mb4;',
    '',
    `${MIGRATIONS_TABLE_DDL};`,
    '',
  ];
  const groups = [
    { dir: MIGRATIONS_DIR, re: MIGRATION_FILE_RE, prefix: '', seed: false },
    { dir: SEED_DIR, re: SEED_FILE_RE, prefix: SEED_ID_PREFIX, seed: true },
  ];
  for (const g of groups) {
    for (const name of listSqlFiles(g.dir, g.re)) {
      const bytes = normalizeBytes(readFileSync(join(g.dir, name)));
      const id = g.prefix + name;
      const sum = checksum(bytes);
      const text = rewriteDirectives(bytes.toString('utf8'), id).trimEnd();
      parts.push(`-- ===================================================================== ${id}`, text, '');
      const record = g.seed
        ? `INSERT INTO fredpd_migrations (id, checksum) VALUES (${sqlString(id)}, '${sum}') ON DUPLICATE KEY UPDATE checksum = VALUES(checksum), applied_at = UTC_TIMESTAMP();`
        : `INSERT INTO fredpd_migrations (id, checksum) VALUES (${sqlString(id)}, '${sum}') ON DUPLICATE KEY UPDATE id = id;`;
      parts.push(record, '');
    }
  }
  parts.push("SELECT 'FredPD database installed' AS result, COUNT(*) AS files_recorded FROM fredpd_migrations;", '');
  return parts.join('\n');
}

const sql = build();
if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== sql) {
    console.error('db/install.sql is stale: run node scripts/gen-install-sql.mjs');
    process.exit(1);
  }
  console.log('db/install.sql is up to date');
} else {
  writeFileSync(OUT, sql);
  console.log(`wrote db/install.sql (${sql.length} bytes)`);
}
